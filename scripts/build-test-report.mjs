/** Builds docs/test-report.md from docs/test-results/*.json. Nothing in the tables is typed by hand except the "Not tested" rows. */
import { readFileSync, writeFileSync } from 'node:fs';

const vitest = JSON.parse(readFileSync('docs/test-results/vitest.json', 'utf8'));
const keyboard = JSON.parse(readFileSync('docs/test-results/keyboard.json', 'utf8'));
const pages = JSON.parse(readFileSync('docs/test-results/pages.json', 'utf8'));
const env = 'Chromium 153.0.8010.12 headless, Linux';
const date = '2026-10-26';
const cell = (s) => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');

const byComponent = new Map();
for (const f of vitest.testResults) {
  const name = f.name.split('/').pop().replace('.stories.tsx', '');
  const list = byComponent.get(name) ?? [];
  for (const a of f.assertionResults) list.push(a);
  byComponent.set(name, list);
}

let out = `# Test report

Generated by \`scripts/build-test-report.mjs\` from the raw results in \`docs/test-results/\`. Date of all runs: ${date}.

## What was and was not tested

| Layer | Tool | Status |
|---|---|---|
| Automated axe-core rules inside every story, in real Chromium | Storybook + Vitest browser mode | Run. ${vitest.numPassedTests} of ${vitest.numTotalTests} pass. |
| Behaviour assertions (play functions) | Testing Library inside the same stories | Run. Included in the count above. |
| Real keyboard events | Playwright keyboard on a dev-only test page | Run. ${keyboard.filter((r) => r.result === 'Pass').length} of ${keyboard.length} pass. |
| Page scans at 1280, 640 and 320 px, four states | axe-core via Playwright | Run. ${pages.filter((r) => r.result === 'Pass').length} of ${pages.length} pass. |
| Screen readers (NVDA, JAWS, VoiceOver, TalkBack) | Human with the software | **Partly tested.** Author ran NVDA with Edge on three items (skip link, first form field, empty submit). All matched in outline. Nothing else. See \`docs/test-results/manual-nvda.md\`. |
| Other browsers (Firefox, Safari) | Manual | **Not tested.** |
| Windows High Contrast / forced colours | Manual | **Not tested.** |
| Browser zoom control at 200% | Manual | **Not tested.** The 640 px viewport scan is a stand-in, not the same thing. |
| Real users with assistive technology | Research kit in \`research/\` | **Not done.** No sessions have been run. |

Automated checks find some problems, not all. Passing axe does not mean the components are accessible. The wording used everywhere is: *tested against relevant WCAG 2.2 AA criteria*, never "compliant".

## Component stories (axe + assertions)

| Component | Test case | Testing method | Expected | Actual | Pass/Fail | Issue observed | Fix applied | Retest result | Environment | Date |
|---|---|---|---|---|---|---|---|---|---|---|
`;
for (const [name, list] of byComponent) {
  for (const a of list) {
    out += `| ${cell(name)} | ${cell(a.title)} | Story play function + axe (color-contrast included) | No axe violations; assertions hold | ${a.status === 'passed' ? 'As expected' : 'See log'} | ${a.status === 'passed' ? 'Pass' : 'Fail'} | See docs/issue-log.md | See docs/issue-log.md | ${a.status === 'passed' ? 'Pass' : 'Fail'} | ${env} | ${date} |\n`;
  }
}

out += `
"Issue observed" and "Fix applied" are in \`docs/issue-log.md\` by entry number, because most problems were found while a story was being written, and not by a finished story. Table cells above say so rather than repeat them.

## Real keyboard checks

| Component | Test case | Testing method | Expected | Actual | Pass/Fail | Issue observed | Fix applied | Retest result | Environment | Date |
|---|---|---|---|---|---|---|---|---|---|---|
`;
for (const r of keyboard) {
  const wasToast = r.component === 'Toast';
  out += `| ${r.component} | ${cell(r.test)} | ${r.method} | ${cell(r.expected)} | ${cell(r.actual)} | ${r.result} | ${wasToast ? 'First run failed. Fault was in my check (log entry 16)' : 'None'} | ${wasToast ? 'Check pressed Tab twice, as the real focus order needs' : 'None'} | ${r.result} | ${r.environment} | ${r.date} |\n`;
}

out += `
## Checkout page scans (viewport width and states)

640 px stands in for 200% zoom on a 1280 px screen. 320 px stands in for 400% zoom (WCAG reflow). This is viewport emulation. It is not the browser zoom control.

| State | Width | What it stands for | Violations (axe, WCAG 2.0/2.1/2.2 A+AA and best-practice tags) | Horizontal page overflow | axe "incomplete" | Pass/Fail |
|---|---|---|---|---|---|---|
`;
for (const r of pages.filter((p) => p.violations)) {
  out += `| ${r.state} | ${r.width} px | ${r.note} | ${r.violations.length === 0 ? 'None' : r.violations.join('; ')} | ${r.pageOverflowPx} px | ${r.incomplete.join(', ') || 'None'} | ${r.result} |\n`;
}
const rm = pages.find((p) => p.measuredMs !== undefined);
out += `
**Reduced motion.** With \`prefers-reduced-motion: reduce\`, the longest computed transition or animation on the page is ${rm.measuredMs} ms. Result: ${rm.result}.

**axe "incomplete" on the bank-select.** axe could not compute the background of the \`<select>\` because it has a chevron background image. I read the computed values: text rgb(29, 28, 25) on background rgb(255, 255, 255), about 16.5:1, and the chevron sits at the right edge, away from the text. Checked by hand. Also covered by the pair list in \`docs/contrast-report.md\`.

## Manual screen reader results (author, NVDA + Edge)

| Check | Reported | Expected | Pass/Fail | Note |
|---|---|---|---|---|
| Skip link is the first Tab stop | "same page, skip to main content" | Skip link announced | Pass | Reported live by the tester, not recorded |
| First form field | "Full name, edit, required" | Name, role, required | Pass | Same |
| Empty submit shows the error summary | "There is a problem", what to fill in, then link "same page" (paraphrase) | Summary title, then error links | Pass in outline | Exact words not captured |
| Focus after Enter on skip link | Not recalled | Focus in main | Not recorded | Tester could not remember |

Full notes in \`docs/test-results/manual-nvda.md\`. Three items from one tester are a start, not coverage.

## Not tested

| Component | Test case | Testing method | Expected | Actual | Pass/Fail | Issue observed | Fix applied | Retest result | Environment | Date |
|---|---|---|---|---|---|---|---|---|---|---|
| 10 of 12 | Announced name, role, state and value | NVDA + Edge on Windows | Matches the "Screen reader" section of each component's docs | Only Text input and the skip link were heard (see above) | **Not tested** | n/a | n/a | n/a | n/a | n/a |
| All 12 | Announced name, role, state and value | VoiceOver + Safari on macOS and iOS | As above | Not run | **Not tested** | n/a | n/a | n/a | n/a | n/a |
| Toast, Alert, Form | Live-region timing | NVDA, VoiceOver | Toast read politely; error Alert read at once; Form summary read on focus | Not run | **Not tested** | n/a | n/a | n/a | n/a | n/a |
| All 12 | Forced colours | Windows High Contrast | Focus ring, borders and state shapes still visible | Not run | **Not tested** | n/a | n/a | n/a | n/a | n/a |
| All 12 | Browser zoom 200% | Chrome zoom control | No loss of content or function | Not run | **Not tested** | n/a | n/a | n/a | n/a | n/a |
| All 12 | Firefox and Safari | Manual | Same behaviour as Chromium | Not run | **Not tested** | n/a | n/a | n/a | n/a | n/a |

## Manual checks for you (about 30 minutes)

Start with NVDA (free, nvaccess.org) and Firefox or Chrome. Open the deployed Storybook or \`npm run storybook\`.

1. Press Tab through the checkout page. Does the skip link come first? Does each control say its name and type?
2. Press the order button with the form empty. Is the error summary read? Does Enter on a summary link land you in the right field?
3. Choose each payment method. Is the change announced?
4. Place a sample order. Is the heading "Sample order created" read? Is the "receipt sent" message read without you moving focus?
5. Open a dialog story. Can you reach anything behind it? Does Escape return you to the button?
6. Write what you heard in \`docs/test-results/manual-nvda.md\`: what you pressed, what was read, what you expected. I will then update this report. I will not guess the results.
`;

writeFileSync('docs/test-report.md', out);
console.log('wrote docs/test-report.md', out.length, 'chars');
