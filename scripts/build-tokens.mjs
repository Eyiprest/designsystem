// Builds tokens from tokens/tokens.json:
//   src/tokens/tokens.css          CSS custom properties (--steady-*)
//   tokens/figma-variables.json    flat list for creating Figma Variables
//   docs/contrast-report.md        computed contrast ratios for every declared pair
// Exits with code 1 if any declared contrast pair misses its minimum.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const src = JSON.parse(readFileSync(resolve(root, 'tokens/tokens.json'), 'utf8'));

/** Flatten nested tokens into [{ path: 'color.bg.canvas', value, description }] */
function flatten(node, trail = []) {
  const out = [];
  for (const [key, val] of Object.entries(node)) {
    if (key.startsWith('$') || key === 'contrast') continue;
    if (val && typeof val === 'object' && '$value' in val) {
      out.push({ path: [...trail, key].join('.'), value: val.$value, description: val.$description ?? '' });
    } else if (val && typeof val === 'object') {
      out.push(...flatten(val, [...trail, key]));
    }
  }
  return out;
}

const tokens = flatten(src);
const byPath = new Map(tokens.map((t) => [t.path, t]));

// ---------- CSS ----------
const cssVar = (path) => `--steady-${path.replace(/\./g, '-')}`;
const css =
  `/* Generated by scripts/build-tokens.mjs from tokens/tokens.json. Do not edit by hand. */\n:root {\n` +
  tokens.map((t) => `  ${cssVar(t.path)}: ${t.value};`).join('\n') +
  `\n}\n`;
mkdirSync(resolve(root, 'src/tokens'), { recursive: true });
writeFileSync(resolve(root, 'src/tokens/tokens.css'), css);

// ---------- Figma variable list ----------
const figmaType = (path, value) => {
  if (path.startsWith('color.')) return 'COLOR';
  if (path.startsWith('font.family')) return 'STRING';
  if (/^[\d.]+(px|ms)$/.test(value) || /^[\d.]+$/.test(value)) return 'FLOAT';
  return 'STRING';
};
const figma = tokens.map((t) => ({
  name: t.path.replace(/\./g, '/'),
  type: figmaType(t.path, t.value),
  value: /^[\d.]+(px|ms)$/.test(t.value) ? parseFloat(t.value) : /^[\d.]+$/.test(t.value) ? parseFloat(t.value) : t.value,
  cssVar: cssVar(t.path),
  description: t.description,
}));
writeFileSync(resolve(root, 'tokens/figma-variables.json'), JSON.stringify(figma, null, 2) + '\n');

// ---------- Contrast ----------
const toRgb = (hex) => {
  const h = hex.replace('#', '');
  return [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16) / 255);
};
const lin = (c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
const lum = (hex) => {
  const [r, g, b] = toRgb(hex).map(lin);
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
const ratio = (a, b) => {
  const [hi, lo] = [lum(a), lum(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
};

const rows = [];
let failed = 0;
for (const [fg, bg, min, sc, use] of src.contrast.pairs) {
  const f = byPath.get(fg), b = byPath.get(bg);
  if (!f || !b) throw new Error(`Unknown token in pair: ${fg} / ${bg}`);
  const r = ratio(f.value, b.value);
  const pass = r >= min;
  if (!pass) failed++;
  rows.push({ fg, bg, fgHex: f.value, bgHex: b.value, r, min, sc, use, pass });
}

const md = [
  '# Contrast report',
  '',
  'Computed by `scripts/build-tokens.mjs` using the WCAG relative luminance formula. Run `npm run tokens` to regenerate.',
  'This checks colour pairs in isolation. It does not check anti-aliasing, text rendered over images, or user-modified colours.',
  '',
  `Result: ${rows.length - failed} of ${rows.length} declared pairs pass.`,
  '',
  '| Foreground | Background | Ratio | Needs | SC | Used for | Result |',
  '|---|---|---|---|---|---|---|',
  ...rows.map(
    (x) =>
      `| \`${x.fg}\` ${x.fgHex} | \`${x.bg}\` ${x.bgHex} | ${x.r.toFixed(2)}:1 | ${x.min}:1 | ${x.sc} | ${x.use} | ${x.pass ? 'Pass' : '**FAIL**'} |`,
  ),
  '',
  '## Not checked by this script',
  '',
  '- `color.text.disabled` on `color.disabled.bg`. Disabled controls are exempt from 1.4.3, so this pair is deliberately not asserted.',
  '- Hover and pressed backgrounds for secondary and ghost buttons are covered by the text pairs above only where they reuse the same background tokens.',
  '',
].join('\n');
writeFileSync(resolve(root, 'docs/contrast-report.md'), md);

for (const x of rows) console.log(`${x.pass ? 'ok  ' : 'FAIL'} ${x.r.toFixed(2).padStart(5)}:1 (need ${x.min}) ${x.fg} on ${x.bg}`);
console.log(`\n${tokens.length} tokens written. ${rows.length - failed}/${rows.length} contrast pairs pass.`);
process.exit(failed ? 1 : 0);
